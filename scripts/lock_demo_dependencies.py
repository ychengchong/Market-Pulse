"""Hash the resolved Linux CPython 3.14 demo wheels without changing the local lock."""
import argparse
import hashlib
from pathlib import Path
import re
import zipfile
from email.parser import BytesParser


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wheels", type=Path, default=Path("data/demo-linux-wheels"))
    parser.add_argument("--output", type=Path, default=Path("demo/requirements.txt"))
    args = parser.parse_args()
    entries = {}
    for wheel in sorted(args.wheels.glob("*.whl")):
        if not ("manylinux" in wheel.name or wheel.name.endswith("none-any.whl")):
            raise ValueError("Only Linux or portable wheels belong in the demo lock")
        with zipfile.ZipFile(wheel) as archive:
            metadata = [n for n in archive.namelist() if n.endswith(".dist-info/METADATA")]
            if len(metadata) != 1:
                raise ValueError("Invalid wheel metadata")
            message = BytesParser().parsebytes(archive.read(metadata[0]))
        name = re.sub(r"[-_.]+", "-", message["Name"]).lower()
        version = message["Version"]
        if name in entries:
            raise ValueError("Resolve into an empty wheel directory to avoid mixed versions")
        entries[name] = f"{name}=={version} --hash=sha256:{hashlib.sha256(wheel.read_bytes()).hexdigest()}"
    if "streamlit" not in entries or any(n.startswith("psycopg") for n in entries):
        raise ValueError("Expected a Streamlit-only demo environment")
    header = "# Frozen demo runtime: CPython 3.14 / Linux x86_64.\n# Generated by python -m scripts.lock_demo_dependencies; local Windows lock is unchanged.\n--only-binary=:all:\n\n"
    args.output.write_text(header + "\n".join(entries[n] for n in sorted(entries)) + "\n", encoding="utf-8")
    print(f"Locked {len(entries)} demo packages with Linux/portable wheel hashes.")


if __name__ == "__main__":
    main()
